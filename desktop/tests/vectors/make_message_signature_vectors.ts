// Produces message_signature_vectors.json with the web app's own code, so the
// desktop and Android apps derive the same signing key and sign the same bytes
// (db/migrations/030, docs/group-keys-and-signatures.md). Not part of any
// build: copy it into ui/src/test/ as makeMessageSignatureVectors.test.ts, run
//
//   cd ui && npx vitest run src/test/makeMessageSignatureVectors.test.ts
//
// and delete the copy. The output lands next to this file (desktop/tests/vectors/).
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { expect, it } from "vitest";
import * as crypto from "../lib/e2eCrypto.js";

// From ui/ (where vitest runs) to desktop/tests/vectors/, where this file lives.
const OUT = resolve(process.cwd(), "../desktop/tests/vectors/message_signature_vectors.json");

const hex = (bytes: Uint8Array) => Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");

it("writes the vectors", async () => {
  await crypto.ready();
  const b64 = crypto.toBase64;
  // Two accounts' X25519 private keys (any 32 bytes are a valid one).
  const accountKeys = [Uint8Array.from({ length: 32 }, (_, i) => i + 1), Uint8Array.from({ length: 32 }, (_, i) => 255 - i * 3)];
  const accounts = accountKeys.map((privateKey) => {
    const pair = crypto.deriveSigningKeyPair(privateKey);
    return { accountPrivateKey: b64(privateKey), signingPublicKey: b64(pair.publicKey), pair };
  });

  const cases = [
    {
      // Upper-case ids are lowered before signing.
      conversationId: "11111111-2222-4333-8444-555555555555",
      senderId: "AAAAAAAA-BBBB-4CCC-8DDD-EEEEEEEEEEEE",
      keyEpoch: 0,
      nonce: Uint8Array.from({ length: 24 }, (_, i) => i),
      ciphertext: Uint8Array.from({ length: 33 }, (_, i) => (i * 7) & 0xff),
      account: 0,
    },
    {
      conversationId: "0f0e0d0c-0b0a-4908-8706-050403020100",
      senderId: "deadbeef-0000-4000-8000-0000feedface",
      keyEpoch: 4294967295,
      nonce: Uint8Array.from({ length: 24 }, () => 0xff),
      ciphertext: new Uint8Array(0),
      account: 1,
    },
    {
      conversationId: "c0ffee00-1234-4abc-9def-001122334455",
      senderId: "0a0b0c0d-0e0f-4a1b-8c2d-3e4f5a6b7c8d",
      keyEpoch: 7,
      nonce: Uint8Array.from({ length: 24 }, (_, i) => 200 - i),
      ciphertext: Uint8Array.from({ length: 300 }, (_, i) => (i * 31 + 5) & 0xff),
      account: 1,
    },
  ].map((c) => {
    const input = crypto.messageSignatureInput(c.conversationId, c.senderId, c.keyEpoch, c.nonce, c.ciphertext);
    const signature = crypto.signMessage(input, accounts[c.account].pair.secretKey);
    expect(crypto.verifyMessageSignature(signature, input, accounts[c.account].pair.publicKey)).toBe(true);
    return {
      conversationId: c.conversationId,
      senderId: c.senderId,
      keyEpoch: c.keyEpoch,
      nonce: b64(c.nonce),
      ciphertext: b64(c.ciphertext),
      account: c.account,
      inputHex: hex(input),
      signature: b64(signature),
    };
  });

  writeFileSync(
    OUT,
    `${JSON.stringify(
      {
        note: "Generated by make_message_signature_vectors.ts from ui/src/lib/e2eCrypto.ts. Signing seed = crypto_kdf_derive_from_key(32, 1, \"rvsignk1\", accountPrivateKey); Ed25519 (crypto_sign_seed_keypair / crypto_sign_detached).",
        accounts: accounts.map(({ accountPrivateKey, signingPublicKey }) => ({ accountPrivateKey, signingPublicKey })),
        cases,
      },
      null,
      2
    )}\n`
  );
});
