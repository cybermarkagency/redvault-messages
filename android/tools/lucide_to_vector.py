"""Converts Lucide SVG icons into Android VectorDrawables.

The desktop app bundles Lucide icons (desktop/app/icons/lucide, ISC
licensed); this turns the ones Android uses into res/drawable XML, so both
apps share one icon set. Lucide icons are 24x24 outlines drawn with a
2-unit round stroke in currentColor, which becomes a black stroke here:
Compose's Icon(tint = ...) recolors it.

    python android/tools/lucide_to_vector.py

Supports the elements Lucide uses: path, circle, rect (with rx/ry) and line.

The design's own icons (desktop/app/icons/ui, the same stroke style) are
converted too, as "ui_<name>" drawables: every name in the folder.
"""

import os
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "desktop", "app", "icons", "lucide")
UI_SOURCE = os.path.join(ROOT, "desktop", "app", "icons", "ui")
# Design icons drawn in the reading direction (mirrored in right-to-left layouts).
UI_MIRRORED = {"chevron-left", "chevron-right", "send", "arrow-up-right", "arrow-down-left", "log-out", "external"}
TARGET = os.path.join(ROOT, "android", "app", "src", "main", "res", "drawable")
SVG = "{http://www.w3.org/2000/svg}"

# drawable name -> (Lucide icon, mirror in right-to-left layouts)
ICONS = {
    "ic_arrow_back": ("arrow-left", True),
    "ic_more_vert": ("ellipsis-vertical", False),
    "ic_lock": ("lock", False),
    "ic_attach": ("paperclip", False),
    "ic_mic": ("mic", False),
    "ic_send": ("send-horizontal", True),
    "ic_file": ("file", False),
    "ic_close": ("x", False),
    "ic_check": ("check", False),
    "ic_check_check": ("check-check", False),
    "ic_shield_check": ("shield-check", False),
    "ic_alert": ("triangle-alert", False),
    "ic_backspace": ("delete", True),
    "ic_circle": ("circle", False),
}


def num(value):
    return f"{float(value):g}"


def circle(e):
    cx, cy, r = (float(e.get(k)) for k in ("cx", "cy", "r"))
    return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0 1,0 {num(2 * r)},0a{num(r)},{num(r)} 0 1,0 {num(-2 * r)},0"


def rect(e):
    x, y = float(e.get("x", 0)), float(e.get("y", 0))
    w, h = float(e.get("width")), float(e.get("height"))
    rx = float(e.get("rx", e.get("ry", 0)))
    ry = float(e.get("ry", rx))
    if rx == 0 and ry == 0:
        return f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
    return (
        f"M{num(x + rx)},{num(y)}h{num(w - 2 * rx)}"
        f"a{num(rx)},{num(ry)} 0 0,1 {num(rx)},{num(ry)}v{num(h - 2 * ry)}"
        f"a{num(rx)},{num(ry)} 0 0,1 {num(-rx)},{num(ry)}h{num(-(w - 2 * rx))}"
        f"a{num(rx)},{num(ry)} 0 0,1 {num(-rx)},{num(-ry)}v{num(-(h - 2 * ry))}"
        f"a{num(rx)},{num(ry)} 0 0,1 {num(rx)},{num(-ry)}z"
    )


def line(e):
    return f"M{num(e.get('x1'))},{num(e.get('y1'))}L{num(e.get('x2'))},{num(e.get('y2'))}"


SHAPES = {"path": lambda e: e.get("d"), "circle": circle, "rect": rect, "line": line}


def convert(lucide_name, mirrored, source=SOURCE, credit="Lucide"):
    tree = ET.parse(os.path.join(source, lucide_name + ".svg"))
    root = tree.getroot()
    width = root.get("stroke-width", "2")
    paths = []
    for element in root.iter():
        tag = element.tag.replace(SVG, "")
        if tag in ("svg", "g"):
            continue
        if tag not in SHAPES:
            raise ValueError(f"{lucide_name}: unsupported element <{tag}>")
        # A shape filled with currentColor (dots, badges) is filled, not stroked.
        filled = element.get("fill") not in (None, "none")
        paths.append((SHAPES[tag](element), filled))
    body = "".join(
        f'''    <path
        android:pathData="{d}"
        android:fillColor="{'#FF000000' if filled else '#00000000'}"
        android:strokeColor="#FF000000"
        android:strokeWidth="{width}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />
'''
        for d, filled in paths
    )
    mirror = '\n    android:autoMirrored="true"' if mirrored else ""
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {credit} "{lucide_name}" ({'ISC license, lucide.dev' if credit == 'Lucide' else 'the app design'}), shared with the desktop app.
     Generated by android/tools/lucide_to_vector.py; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24"{mirror}>
{body}</vector>
'''


def main():
    for drawable, (lucide_name, mirrored) in ICONS.items():
        with open(os.path.join(TARGET, drawable + ".xml"), "w", encoding="utf-8", newline="\n") as out:
            out.write(convert(lucide_name, mirrored))
        print(f"{drawable}.xml  <-  {lucide_name}")
    for file in sorted(os.listdir(UI_SOURCE)):
        if not file.endswith(".svg"):
            continue
        name = file[:-4]
        drawable = "ui_" + name.replace("-", "_")
        with open(os.path.join(TARGET, drawable + ".xml"), "w", encoding="utf-8", newline="\n") as out:
            out.write(convert(name, name in UI_MIRRORED, UI_SOURCE, "Design icon"))
        print(f"{drawable}.xml  <-  ui/{name}")


if __name__ == "__main__":
    main()
